#!/usr/bin/env python3
"""Rewrites `async` test methods so a selector-based runner can call them.

Swift `async` methods use a different calling convention and cannot be reached
through a selector, which is how XCTest discovers tests. This script wraps the
body of every `func test…() async throws` in `runAsync { … }`, which waits on the
task to completion. The body itself is untouched, so the same test source runs
under XCTest and under `Scripts/run-tests.sh`.

Usage: rewrite-async-tests.py <tests-dir> <out-dir>
"""

from __future__ import annotations

import pathlib
import re
import sys

PATTERN = re.compile(
    r"^(?P<indent>[ \t]*)"
    r"func (?P<name>test\w+)\(\) async(?: throws)? \{\n"
    r"(?P<body>.*?)"
    r"^(?P=indent)\}\n",
    re.MULTILINE | re.DOTALL,
)


def add_throws(text: str) -> str:
    """Marks every test method `throws`, because the assertions throw."""
    return re.sub(
        r"^(\s*)func (test\w+)\(\) \{",
        r"\1func \2() throws {",
        text,
        flags=re.MULTILINE,
    )


def rewrite(text: str) -> str:
    def replace(match: re.Match) -> str:
        indent = match.group("indent")
        name = match.group("name")
        body = match.group("body")
        indented = "\n".join(
            ("        " + line) if line.strip() else line
            for line in body.splitlines()
        )
        return (
            f"{indent}func {name}() throws {{\n"
            f"{indent}    try runAsync {{ [self] in\n"
            f"{indented}\n"
            f"{indent}    }}\n"
            f"{indent}}}\n"
        )

    return add_throws(PATTERN.sub(replace, text))


CLASS_PATTERN = re.compile(r"^(?:final )?class (\w+Tests)\s*:\s*XCTestCase", re.MULTILINE)
TEST_PATTERN = re.compile(r"^\s*func (test\w+)\(\)", re.MULTILINE)


def registry_entry(name: str, text: str) -> str:
    """Builds the list of test methods for one class.

    Each entry is a closure that constructs the suite, runs its fixture hooks and
    calls the method. Calling through a closure rather than a selector keeps the
    test methods out of the Objective-C runtime entirely, which is how XCTest
    reaches them but not something a minimal runner needs.
    """
    methods = TEST_PATTERN.findall(text)
    lines = []
    for method in methods:
        lines.append(
            f'        ("{name}", "{method}", {{ \n'
            f'            let instance = {name}()\n'
            f'            instance.setUp()\n'
            f'            defer {{ instance.tearDown() }}\n'
            f'            try? instance.setUpWithError()\n'
            f'            defer {{ try? instance.tearDownWithError() }}\n'
            f'            try instance.{method}()\n'
            f'        }}),'
        )
    return "\n".join(lines)


def main() -> int:
    if len(sys.argv) != 3:
        print(__doc__)
        return 2
    source_dir = pathlib.Path(sys.argv[1])
    target_dir = pathlib.Path(sys.argv[2])
    target_dir.mkdir(parents=True, exist_ok=True)

    rewritten = 0
    entries: list[str] = []
    for source in sorted(source_dir.glob("*.swift")):
        text = source.read_text(encoding="utf-8")
        result = rewrite(text)
        if result != text:
            rewritten += 1
        (target_dir / source.name).write_text(result, encoding="utf-8")
        for class_name in CLASS_PATTERN.findall(result):
            class_body = result.split(f"class {class_name}", 1)[1]
            entries.append(registry_entry(class_name, class_body))

    # An explicit registry, rather than runtime discovery: walking every class in
    # the process sends messages to AppKit internals that abort when asked.
    registry = [
        "import Foundation",
        "import XCTest",
        "",
        "/// Generated by Scripts/rewrite-async-tests.py.",
        "struct TestRegistry {",
        "    nonisolated(unsafe) static let all: [(suite: String, method: String, body: () throws -> Void)] = [",
        *entries,
        "    ]",
        "}",
        "",
    ]
    (target_dir / "TestRegistry.swift").write_text("\n".join(registry), encoding="utf-8")
    print(f"  rewrote {rewritten} of {len(list(source_dir.glob('*.swift')))} files, registered {sum(len(e.splitlines()) for e in entries)} tests")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
